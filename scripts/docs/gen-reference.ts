const unwrap = (e: ts.Expression): ts.Expression =>
  ts.isAsExpression(e) || ts.isSatisfiesExpression(e) || ts.isParenthesizedExpression(e)
    ? unwrap(e.expression)
    : e

/** The object literal a local `function f() { return {…} }` returns, for a `f()` definition. */
function returnedObject(
  call: ts.CallExpression,
  sf: ts.SourceFile,
): ts.ObjectLiteralExpression | undefined {
  if (!ts.isIdentifier(call.expression) || call.arguments.length > 0) return undefined
  const fnName = call.expression.text
  let found: ts.ObjectLiteralExpression | undefined
  const visit = (n: ts.Node): void => {
    if (found) return
    if (ts.isFunctionDeclaration(n) && n.name?.text === fnName && n.body) {
      const ret = n.body.statements.find(ts.isReturnStatement)
      const e = ret?.expression ? unwrap(ret.expression) : undefined
      if (e && ts.isObjectLiteralExpression(e)) found = e
      return
    }
    ts.forEachChild(n, visit)
  }
  visit(sf)
  return found
}

/**
 * The definitions a `for (const t of defs)` loop around `node` iterates, when
 * `defs` is an array literal (inline or a const in this file): each element's
 * properties, keyed by the loop variable's name.
 */
function loopBindings(
  node: ts.Node,
  varName: string,
  sf: ts.SourceFile,
): Map<string, ts.Expression>[] | undefined {
  for (let p: ts.Node | undefined = node.parent; p; p = p.parent) {
    if (!ts.isForOfStatement(p) || !ts.isVariableDeclarationList(p.initializer)) continue
    const d = p.initializer.declarations[0]
    if (!d || !ts.isIdentifier(d.name) || d.name.text !== varName) continue
    let iter = unwrap(p.expression)
    if (ts.isIdentifier(iter)) {
      const init = findVariable(sf, iter.text)?.initializer
      if (!init) return undefined
      iter = unwrap(init)
    }
    if (!ts.isArrayLiteralExpression(iter)) return undefined
    const out: Map<string, ts.Expression>[] = []
    for (const el of iter.elements) {
      if (!ts.isObjectLiteralExpression(el)) return undefined
      out.push(objectProps(el))
    }
    return out
  }
  return undefined
}

/** `{ ...entry, handler: wrap(entry.handler) }`: re-registers a tool already registered elsewhere. */
function isReregistration(def: ts.Expression): boolean {
  const d = unwrap(def)
  return (
    ts.isObjectLiteralExpression(d) &&
    d.properties.some((p) => ts.isSpreadAssignment(p) && ts.isIdentifier(p.expression)) &&
    !d.properties.some(
      (p) => ts.isPropertyAssignment(p) && ts.isIdentifier(p.name) && p.name.text === "description",
    )
  )
}

/** A string array literal, or a const in this file naming one; anything else reads as none. */
function resolveStringArray(e: ts.Expression, sf: ts.SourceFile): string[] {
  let arr = unwrap(e)
  if (ts.isIdentifier(arr)) {
    const init = findVariable(sf, arr.text)?.initializer
    if (!init) return []
    arr = unwrap(init)
  }
  if (!ts.isArrayLiteralExpression(arr)) return []
  return arr.elements.flatMap((el) => {
    if (ts.isSpreadElement(el)) return resolveStringArray(el.expression, sf)
    const v = stringValue(el as ts.Expression)
    return v === undefined ? [] : [v]
  })
}

function insideCondition(node: ts.Node): boolean {
  for (let p: ts.Node | undefined = node.parent; p; p = p.parent) {
    if (ts.isIfStatement(p) || ts.isConditionalExpression(p)) return true
    if (ts.isSourceFile(p)) return false
  }
  return false
}

/**
 * Kernel agent tools: every `toolRegistry.set([orgId, "kernel", <name>], <def>)`
 * in non-test files under apps/api/src/modules. The name is a literal, or
 * `t.name` inside a `for (const t of <array literal>)` loop (one tool per
 * element); the definition is an object literal or a call to a local function
 * returning one. Descriptions and scopes may be constants (this file or an
 * import). A registration that re-wraps an existing entry (`{ ...entry, … }`)
 * adds no tool. Anything else, an unresolvable scope included, throws with the
 * tool (or file) named: the page never prints a guess.
 */
export function collectKernelTools(root: string = ROOT): KernelTools {
  const files: string[] = []
  walkSources(join(root, "apps/api/src/modules"), files)
  const byName = new Map<string, KernelTools["tools"][number]>()
  for (const f of files) {
    const text = readFileSync(f, "utf8")
    if (!text.includes("toolRegistry.set(")) continue
    const file = relative(root, f)
    const sf = ts.createSourceFile(f, text, ts.ScriptTarget.Latest, true)
    const ctx: ZodCtx = { sf, root, file }
    const where = (n: ts.Node) =>
      `${file}:${sf.getLineAndCharacterOfPosition(n.getStart(sf)).line + 1}`
    const visit = (n: ts.Node): void => {
      ts.forEachChild(n, visit)
      if (
        !ts.isCallExpression(n) ||
        !ts.isPropertyAccessExpression(n.expression) ||
        n.expression.name.text !== "set" ||
        n.expression.expression.getText(sf) !== "toolRegistry"
      ) {
        return
      }
      const key = n.arguments[0]
      const def = n.arguments[1]
      if (!key || !ts.isArrayLiteralExpression(key) || key.elements.length !== 3) return
      const app = key.elements[1]
      if (!app || !ts.isStringLiteral(app) || app.text !== "kernel") return
      const nameExpr = key.elements[2] as ts.Expression
      if (!def) throw new Error(`${where(n)}: kernel tool registration without a definition`)
      if (isReregistration(def)) return

      // One binding per registered tool: none for a literal name, one per loop element.
      let bindings: Array<{ loopVar?: string; props?: Map<string, ts.Expression> }> = [{}]
      if (
        ts.isPropertyAccessExpression(nameExpr) &&
        ts.isIdentifier(nameExpr.expression) &&
        !ts.isStringLiteral(nameExpr)
      ) {
        const loopVar = nameExpr.expression.text
        const els = loopBindings(n, loopVar, sf)
        if (!els) {
          throw new Error(
            `${where(n)}: kernel tool name \`${nameExpr.getText(sf)}\` is not a loop over an array literal`,
          )
        }
        bindings = els.map((props) => ({ loopVar, props }))
      } else if (!ts.isStringLiteral(nameExpr)) {
        throw new Error(
          `${where(n)}: kernel tool name \`${nameExpr.getText(sf)}\` cannot be resolved`,
        )
      }

      const d0 = unwrap(def)
      const defObj = ts.isObjectLiteralExpression(d0)
        ? d0
        : ts.isCallExpression(d0)
          ? returnedObject(d0, sf)
          : undefined
      if (!defObj) {
        throw new Error(
          `${where(n)}: kernel tool definition \`${def.getText(sf)}\` cannot be resolved`,
        )
      }
      const defProps = objectProps(defObj)

      for (const b of bindings) {
        // `t.description` → the loop element's `description` expression.
        const bound = (e: ts.Expression | undefined): ts.Expression | undefined => {
          if (!e) return undefined
          const u = unwrap(e)
          if (
            b.loopVar &&
            ts.isPropertyAccessExpression(u) &&
            ts.isIdentifier(u.expression) &&
            u.expression.text === b.loopVar
          ) {
            return b.props?.get(u.name.text)
          }
          return u
        }
        const nameNode = bound(nameExpr)
        const name = nameNode ? resolveString(nameNode, ctx) : undefined
        if (!name) throw new Error(`${where(n)}: kernel tool name cannot be resolved`)

        const scopesExpr = bound(defProps.get("requiredScopes"))
        if (!scopesExpr) throw new Error(`${where(n)}: kernel tool ${name} has no requiredScopes`)
        let scopesArr: ts.Expression = scopesExpr
        if (ts.isIdentifier(scopesArr)) {
          const init = findVariable(sf, scopesArr.text)?.initializer
          if (init) scopesArr = unwrap(init)
        }
        if (!ts.isArrayLiteralExpression(scopesArr)) {
          throw new Error(
            `${where(n)}: kernel tool ${name}: requiredScopes \`${scopesExpr.getText(sf)}\` cannot be resolved`,
          )
        }
        const requiredScopes = scopesArr.elements.map((e) => {
          const v = resolveString(e as ts.Expression, ctx)
          if (v === undefined) {
            throw new Error(
              `${where(n)}: kernel tool ${name}: scope \`${e.getText(sf)}\` cannot be resolved to a string`,
            )
          }
          return v
        })

        const dExpr = bound(defProps.get("description"))
        const fullDescription = (dExpr ? resolveString(dExpr, ctx) : undefined) ?? ""
        const description = firstSentence(fullDescription || undefined)
        const gatedExpr = bound(defProps.get("gated"))
        const gated = gatedExpr?.kind === ts.SyntaxKind.TrueKeyword
        const flag = (key: string): boolean | undefined => {
          const e = bound(defProps.get(key))
          if (e?.kind === ts.SyntaxKind.TrueKeyword) return true
          if (e?.kind === ts.SyntaxKind.FalseKeyword) return false
          return undefined
        }
        const keywordsExpr = bound(defProps.get("searchKeywords"))
        const paramsExpr = bound(defProps.get("params"))

        let availability: string | undefined
        if (insideCondition(n) && bindings.length === 1) {
          availability = CONDITIONAL_KERNEL_TOOLS[name]
          if (!availability) {
            throw new Error(
              `${where(n)}: kernel tool ${name} is registered under a condition; state it in CONDITIONAL_KERNEL_TOOLS`,
            )
          }
        }

        const prev = byName.get(name)
        const deferLoading = flag("deferLoading") ?? prev?.deferLoading
        byName.set(name, {
          name,
          description: description || prev?.description || "",
          gated: gated || prev?.gated === true,
          requiredScopes,
          fullDescription: fullDescription || prev?.fullDescription || "",
          searchKeywords: keywordsExpr
            ? resolveStringArray(keywordsExpr, sf)
            : (prev?.searchKeywords ?? []),
          ...(deferLoading !== undefined ? { deferLoading } : {}),
          agentVisible: flag("agentVisible") !== false && prev?.agentVisible !== false,
          routineOnly: flag("routineOnly") === true || prev?.routineOnly === true,
          paramsChars: paramsExpr ? paramsExpr.getText(sf).length : (prev?.paramsChars ?? 0),
          ...((availability ?? prev?.availability)
            ? { availability: availability ?? prev?.availability }
            : {}),
        })
      }
    }
    visit(sf)
  }
  return { tools: [...byName.values()].sort((a, b) => a.name.localeCompare(b.name)) }
}

function toolRows(tools: Array<AgentTool & { availability?: string }>): string[][] {
  return tools.map((t) => [
    code(t.name),
    cell([t.description, t.availability].filter(Boolean).join(" ")),
    t.gated ? "yes" : "",
    t.requiredScopes.map(code).join(", "),
  ])
}

export function renderAgentTools(kernel: KernelTools, apps: AppTools[]): string {
  const head = ["Tool", "Description", "Approval-gated", "Required scopes"]
  const out: string[] = [
    "The tools an agent can call. An agent sees a tool only when its role holds the tool's required scopes. An approval-gated tool queues its action for a person to approve before it runs; an org approval policy can gate other tools too.",
    "",
    "## Kernel tools",
    "",
  ]
  if (kernel.tools.length > 0) out.push(table(head, toolRows(kernel.tools)), "")
  for (const a of apps) {
    out.push(`## ${a.app}`, "")
    if (a.summary) out.push(cell(a.summary), "")
    out.push(table(head, toolRows(a.tools)), "")
  }
  return page(
    "Agent tools reference",
    "Every agent tool the kernel and the shipped apps provide, with its required scopes and whether it needs approval.",
    "the kernel tool registrations and the shipped app manifests",
    out.join("\n"),
  )
}

