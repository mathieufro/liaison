export interface ZodField {
  key: string
  desc: ZodDesc
  /** The key's own leading comment, one paragraph. */
  comment: string
}

export interface ZodDesc {
  kind: "primitive" | "enum" | "object" | "array" | "record" | "union" | "unknown"
  /** Human type for primitives and enums (`string`, `"a" | "b"`). */
  type?: string
  optional: boolean
  nullable: boolean
  default?: string
  fields?: ZodField[]
  element?: ZodDesc
  variants?: ZodDesc[]
  /** The leading comment of the variable this schema came from, if any. */
  varComment?: string
}

interface ZodCtx {
  sf: ts.SourceFile
  /** The repo root, to resolve `~/` imports of default values. */
  root: string
  /** Path of the file under `root`, for relative imports. */
  file: string
}

const PASSTHROUGH = new Set([
  "min",
  "max",
  "int",
  "trim",
  "regex",
  "positive",
  "nonnegative",
  "negative",
  "gt",
  "gte",
  "lt",
  "lte",
  "length",
  "strict",
  "passthrough",
  "refine",
  "superRefine",
  "transform",
  "describe",
  "catch",
  "toLowerCase",
  "toUpperCase",
  "nonempty",
  "finite",
  "startsWith",
  "endsWith",
])
const FORMATS: Record<string, string> = { url: "URL", email: "email", uuid: "UUID" }

function findVariable(sf: ts.SourceFile, name: string): ts.VariableDeclaration | undefined {
  let found: ts.VariableDeclaration | undefined
  const visit = (n: ts.Node): void => {
    if (found) return
    if (ts.isVariableDeclaration(n) && ts.isIdentifier(n.name) && n.name.text === name) found = n
    else ts.forEachChild(n, visit)
  }
  visit(sf)
  return found
}

function variableStatement(decl: ts.VariableDeclaration): ts.Node {
  return decl.parent?.parent && ts.isVariableStatement(decl.parent.parent)
    ? decl.parent.parent
    : decl
}

/** A literal's display text, or undefined when the expression is not a literal. */
function literalText(e: ts.Expression): string | undefined {
  if (ts.isStringLiteral(e) || ts.isNoSubstitutionTemplateLiteral(e)) return JSON.stringify(e.text)
  if (ts.isNumericLiteral(e)) return String(Number(e.text.replace(/_/g, "")))
  if (e.kind === ts.SyntaxKind.TrueKeyword) return "true"
  if (e.kind === ts.SyntaxKind.FalseKeyword) return "false"
  if (e.kind === ts.SyntaxKind.NullKeyword) return "null"
  if (ts.isPrefixUnaryExpression(e) && ts.isNumericLiteral(e.operand)) {
    return `-${Number(e.operand.text.replace(/_/g, ""))}`
  }
  if (ts.isArrayLiteralExpression(e) && e.elements.length === 0) return "[]"
  return undefined
}

/** Resolve an identifier to a literal: a const in this file or in an imported `~/`/relative module. */
function resolveIdentifierLiteral(
  name: string,
  ctx: ZodCtx,
  depth = 0,
  extract: (e: ts.Expression) => string | undefined = literalText,
): string | undefined {
  if (depth > 3) return undefined
  const local = findVariable(ctx.sf, name)
  if (local?.initializer) {
    const lit = extract(local.initializer)
    if (lit !== undefined) return lit
    if (ts.isAsExpression(local.initializer)) return extract(local.initializer.expression)
  }
  for (const stmt of ctx.sf.statements) {
    if (!ts.isImportDeclaration(stmt) || !ts.isStringLiteral(stmt.moduleSpecifier)) continue
    const bindings = stmt.importClause?.namedBindings
    if (!bindings || !ts.isNamedImports(bindings)) continue
    if (!bindings.elements.some((el) => el.name.text === name)) continue
    const spec = stmt.moduleSpecifier.text
    let target: string | undefined
    if (spec.startsWith("~/")) target = `apps/api/src/${spec.slice(2)}`
    else if (spec.startsWith(".")) target = join(dirname(ctx.file), spec)
    if (!target) return undefined
    const file = [`${target}.ts`, `${target}/index.ts`].find((f) => existsSync(join(ctx.root, f)))
    if (!file) return undefined
    const sf = parseFile(join(ctx.root, file))
    return resolveIdentifierLiteral(name, { sf, root: ctx.root, file }, depth + 1, extract)
  }
  return undefined
}

function defaultText(e: ts.Expression, ctx: ZodCtx): string {
  const lit = literalText(e)
  if (lit !== undefined) return lit
  if (ts.isIdentifier(e)) return resolveIdentifierLiteral(e.text, ctx) ?? e.text
  return e.getText(ctx.sf).replace(/\s+/g, " ")
}

function enumType(arg: ts.Expression | undefined, ctx: ZodCtx): string {
  if (!arg) return "enum"
  let e: ts.Expression = arg
  if (ts.isIdentifier(e)) {
    const v = findVariable(ctx.sf, e.text)
    if (v?.initializer) e = v.initializer
    else return `one of ${e.text}`
  }
  if (ts.isAsExpression(e)) e = e.expression
  if (ts.isArrayLiteralExpression(e)) {
    return e.elements
      .map((el) => literalText(el as ts.Expression) ?? el.getText(ctx.sf))
      .join(" | ")
  }
  return `one of ${e.getText(ctx.sf)}`
}

function blank(kind: ZodDesc["kind"], type?: string): ZodDesc {
  return { kind, ...(type ? { type } : {}), optional: false, nullable: false }
}

/** Describe a zod schema expression, statically. */
export function describeZod(expr: ts.Expression, ctx: ZodCtx, seen = new Set<string>()): ZodDesc {
  if (ts.isParenthesizedExpression(expr)) return describeZod(expr.expression, ctx, seen)
  if (ts.isAsExpression(expr) || ts.isSatisfiesExpression(expr)) {
    return describeZod(expr.expression, ctx, seen)
  }
  if (ts.isIdentifier(expr)) {
    const decl = findVariable(ctx.sf, expr.text)
    if (decl?.initializer && !seen.has(expr.text)) {
      const inner = describeZod(decl.initializer, ctx, new Set([...seen, expr.text]))
      const comment = joinParagraph(leadingCommentLines(variableStatement(decl), ctx.sf))
      return comment && !inner.varComment ? { ...inner, varComment: comment } : inner
    }
    return blank("unknown", expr.text)
  }
  if (!ts.isCallExpression(expr)) return blank("unknown", expr.getText(ctx.sf))
  const callee = expr.expression
  const args = expr.arguments
  // envBoolean(default): a strict boolean with that default.
  if (ts.isIdentifier(callee) && callee.text === "envBoolean") {
    return {
      ...blank("primitive", "boolean"),
      optional: true,
      ...(args[0] ? { default: defaultText(args[0], ctx) } : {}),
    }
  }
  if (!ts.isPropertyAccessExpression(callee)) return blank("unknown", expr.getText(ctx.sf))
  const method = callee.name.text
  const target = callee.expression
  const isZ = ts.isIdentifier(target) && target.text === "z"
  const isCoerce =
    ts.isPropertyAccessExpression(target) &&
    target.name.text === "coerce" &&
    ts.isIdentifier(target.expression) &&
    target.expression.text === "z"
  if (isZ || isCoerce) {
    switch (method) {
      case "string":
      case "number":
      case "boolean":
      case "date":
      case "bigint":
        return blank("primitive", method)
      case "unknown":
      case "any":
        return blank("unknown", method)
      case "literal":
        return blank("enum", args[0] ? (literalText(args[0]) ?? args[0].getText(ctx.sf)) : "")
      case "enum":
        return blank("enum", enumType(args[0], ctx))
      case "object": {
        const fields: ZodField[] = []
        const obj = args[0]
        if (obj && ts.isObjectLiteralExpression(obj)) {
          for (const p of obj.properties) {
            if (!ts.isPropertyAssignment(p)) continue
            const key = ts.isIdentifier(p.name) || ts.isStringLiteral(p.name) ? p.name.text : ""
            if (!key) continue
            fields.push({
              key,
              desc: describeZod(p.initializer, ctx, seen),
              comment: joinParagraph(leadingCommentLines(p, ctx.sf)),
            })
          }
        }
        return { ...blank("object"), fields }
      }
      case "array":
        return {
          ...blank("array"),
          element: args[0] ? describeZod(args[0], ctx, seen) : blank("unknown"),
        }
      case "record":
        return {
          ...blank("record"),
          element: args[1] ? describeZod(args[1], ctx, seen) : blank("unknown"),
        }
      case "union": {
        const arr = args[0]
        const variants =
          arr && ts.isArrayLiteralExpression(arr)
            ? arr.elements.map((el) => describeZod(el as ts.Expression, ctx, seen))
            : []
        return { ...blank("union"), variants }
      }
      case "preprocess":
        return args[1] ? describeZod(args[1], ctx, seen) : blank("unknown")
      default:
        return blank("unknown", method)
    }
  }
  const inner = describeZod(target, ctx, seen)
  if (method === "optional") return { ...inner, optional: true }
  if (method === "nullable") return { ...inner, nullable: true }
  if (method === "nullish") return { ...inner, optional: true, nullable: true }
  if (method === "default") {
    return { ...inner, ...(args[0] ? { default: defaultText(args[0], ctx) } : {}) }
  }
  if (FORMATS[method]) return { ...inner, type: `${inner.type ?? "string"} (${FORMATS[method]})` }
  if (PASSTHROUGH.has(method)) return inner
  return inner
}

/** Short type text for a table cell. */
export function typeText(d: ZodDesc): string {
  let t: string
  switch (d.kind) {
    case "primitive":
    case "enum":
    case "unknown":
      t = d.type ?? "unknown"
      break
    case "object":
      t = "object"
      break
    case "array":
      t = d.element ? `${typeText({ ...d.element, nullable: false })}[]` : "array"
      if (d.element && /[| ]/.test(typeText(d.element))) t = `(${typeText(d.element)})[]`
      break
    case "record":
      t = `map of ${d.element ? typeText(d.element) : "unknown"}`
      break
    case "union": {
      const variants = d.variants ?? []
      t =
        variants.length > 1 && variants.every((v) => v.kind === "object")
          ? `object (${variants.length} forms)`
          : variants.map((v) => typeText(v)).join(" | ")
      break
    }
  }
  return d.nullable ? `${t} | null` : t
}

export function parseFile(path: string): ts.SourceFile {
  return ts.createSourceFile(path, readFileSync(path, "utf8"), ts.ScriptTarget.Latest, true)
}

function findSchemaObject(sf: ts.SourceFile, varName: string): ts.ObjectLiteralExpression | null {
  const decl = findVariable(sf, varName)
  let found: ts.ObjectLiteralExpression | null = null
  const visit = (n: ts.Node): void => {
    if (found) return
    if (
      ts.isCallExpression(n) &&
      ts.isPropertyAccessExpression(n.expression) &&
      n.expression.name.text === "object" &&
      ts.isIdentifier(n.expression.expression) &&
      n.expression.expression.text === "z" &&
      n.arguments[0] &&
      ts.isObjectLiteralExpression(n.arguments[0])
    ) {
      found = n.arguments[0]
      return
    }
    ts.forEachChild(n, visit)
  }
  if (decl?.initializer) visit(decl.initializer)
  return found
}

