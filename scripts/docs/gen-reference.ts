function flatten(prefix: string, d: ZodDesc, rows: ConfigRow[], note = ""): void {
  const children: { prefix: string; desc: ZodDesc } | null =
    d.kind === "object"
      ? { prefix, desc: d }
      : (d.kind === "array" || d.kind === "record") && d.element
        ? { prefix: d.kind === "array" ? `${prefix}[]` : `${prefix}.<key>`, desc: d.element }
        : null
  if (!children) return
  const target = children.desc
  if (target.kind === "object") {
    for (const f of target.fields ?? []) {
      const own = f.comment || f.desc.varComment || f.desc.element?.varComment || ""
      const description = [note, own].filter(Boolean).join(" ")
      const path = `${children.prefix}.${f.key}`
      rows.push({
        path,
        type: typeText(f.desc),
        required: !f.desc.optional && f.desc.default === undefined,
        ...(f.desc.default !== undefined ? { default: f.desc.default } : {}),
        description,
      })
      flatten(path, f.desc, rows)
    }
  } else if (target.kind === "union") {
    ;(target.variants ?? []).forEach((v, i) => {
      if (v.kind === "object") flatten(children.prefix, v, rows, `Form ${i + 1}.`)
    })
  }
}

export function collectConfigSchema(
  source: string,
  opts: { root?: string; file?: string } = {},
): ConfigSection[] {
  const file = opts.file ?? SOURCES.config
  const sf = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true)
  const ctx: ZodCtx = { sf, root: opts.root ?? ROOT, file }
  const obj = findSchemaObject(sf, "configSchema")
  if (!obj) throw new Error(`${file}: no \`configSchema = z.object({...})\` found`)
  const sections: ConfigSection[] = []
  for (const p of obj.properties) {
    if (!ts.isPropertyAssignment(p)) continue
    const key = ts.isIdentifier(p.name) || ts.isStringLiteral(p.name) ? p.name.text : ""
    if (!key) continue
    const desc = describeZod(p.initializer, ctx)
    const rows: ConfigRow[] = []
    flatten(key, desc, rows)
    sections.push({
      key,
      type: typeText(desc),
      required: !desc.optional && desc.default === undefined,
      description: joinParagraph(leadingCommentLines(p, sf)) || desc.varComment || "",
      rows,
    })
  }
  return sections
}

