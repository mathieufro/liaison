/** One table cell: `|` escaped everywhere, `<`/`>` escaped outside code spans, one line. */
export function cell(text: string | undefined): string {
  if (!text) return ""
  const oneLine = text.replace(/\s*\n\s*/g, " ").trim()
  return oneLine
    .split(/(`[^`]*`)/)
    .map((part, i) =>
      i % 2 === 1
        ? part.replace(/\|/g, "\\|")
        : part.replace(/\|/g, "\\|").replace(/</g, "&lt;").replace(/>/g, "&gt;"),
    )
    .join("")
}

/** A code span that survives any content (backticks in it widen the fence). */
export function code(text: string): string {
  const fence = text.includes("`") ? "``" : "`"
  const pad = text.startsWith("`") || text.endsWith("`") ? " " : ""
  return `${fence}${pad}${text}${pad}${fence}`
}

export function table(head: string[], rows: string[][]): string {
  const lines = [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`]
  // A literal `|` inside a cell (code spans included) must be escaped in GFM.
  for (const r of rows)
    lines.push(`| ${r.map((c) => c.replace(/(?<!\\)\|/g, "\\|")).join(" | ")} |`)
  return lines.join("\n")
}

function page(title: string, description: string, source: string, body: string): string {
  return [
    "---",
    `title: ${JSON.stringify(title)}`,
    `description: ${JSON.stringify(description)}`,
    "---",
    "",
    `Generated by \`bun run docs:gen\` from ${source}. Do not edit.`,
    "",
    body.trimEnd(),
    "",
  ].join("\n")
}

/** The first sentence of a description (up to the first `. ` / end). */
export function firstSentence(text: string | undefined): string {
  if (!text) return ""
  const flat = text.replace(/\s+/g, " ").trim()
  const m = /^(.+?[.!?])(\s|$)/.exec(flat)
  return m?.[1] ?? flat
}

