export interface EnvSchemaEntry {
  name: string
  type: string
  default?: string
  required: boolean
  description: string
  /** The banner section it sits under (`// ── Title ──`), or null. */
  group: string | null
}

export interface EnvGroup {
  title: string | null
  intro: string
}

/** Every key of `envSchema` in an env.ts source text. */
export function collectEnvSchema(
  source: string,
  opts: { root?: string; file?: string } = {},
): { entries: EnvSchemaEntry[]; groups: EnvGroup[] } {
  const file = opts.file ?? SOURCES.env
  const sf = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true)
  const ctx: ZodCtx = { sf, root: opts.root ?? ROOT, file }
  const obj = findSchemaObject(sf, "envSchema")
  if (!obj) throw new Error(`${file}: no \`envSchema = z.object({...})\` found`)
  const entries: EnvSchemaEntry[] = []
  const groups: EnvGroup[] = [{ title: null, intro: "" }]
  let group: string | null = null
  for (const p of obj.properties) {
    if (!ts.isPropertyAssignment(p)) continue
    const name = ts.isIdentifier(p.name) || ts.isStringLiteral(p.name) ? p.name.text : ""
    if (!name) continue
    const lines = leadingCommentLines(p, sf)
    let start = 0
    for (let i = 0; i < lines.length; i++) {
      const m = BANNER.exec(lines[i]?.trim() ?? "")
      if (!m?.[1]) continue
      start = i + 1
      if (/^end\b/i.test(m[1])) {
        group = null
        continue
      }
      group = m[1]
      // The paragraph right after an opening banner introduces the section.
      const intro: string[] = []
      while (start < lines.length && lines[start]?.trim() !== "") intro.push(lines[start++] ?? "")
      if (!groups.some((g) => g.title === group)) {
        groups.push({ title: group, intro: joinParagraph(intro) })
      }
    }
    const desc = describeZod(p.initializer, ctx)
    entries.push({
      name,
      type: typeText(desc),
      ...(desc.default !== undefined ? { default: desc.default } : {}),
      required: !desc.optional && desc.default === undefined,
      description: joinParagraph(lines.slice(start)),
      group,
    })
  }
  return { entries, groups }
}

export interface EnvUsage {
  name: string
  /** `path:line` of every non-test read, sorted. */
  files: string[]
}

const SKIP_DIRS = new Set([
  "node_modules",
  "dist",
  "build",
  ".turbo",
  "coverage",
  "tests",
  "__tests__",
  "__fixtures__",
  "fixtures",
  "e2e",
  "test-results",
  "test-support",
  ".vite",
  // Developer and CI tooling, not the running product.
  "scripts",
  "ci",
  "vendor",
])

function isTestFile(name: string): boolean {
  return (
    /\.(test|spec|e2e|testutil)\.[cm]?[jt]sx?$/.test(name) ||
    /\.config\.[cm]?[jt]s$/.test(name) ||
    /^test-/.test(name)
  )
}

function walkSources(dir: string, out: string[]): void {
  if (!existsSync(dir)) return
  for (const entry of readdirSync(dir).sort()) {
    if (entry.startsWith(".")) continue
    const full = join(dir, entry)
    const st = statSync(full)
    if (st.isDirectory()) {
      if (!SKIP_DIRS.has(entry)) walkSources(full, out)
    } else if (/\.[cm]?[jt]sx?$/.test(entry) && !entry.endsWith(".d.ts") && !isTestFile(entry)) {
      out.push(full)
    }
  }
}

const ENV_READ =
  /\b(?:process\.env|Bun\.env|import\.meta\.env)(?:\.([A-Z_][A-Z0-9_]*)|\[\s*["'`]([A-Z_][A-Z0-9_]*)["'`]\s*\])|\benvFlag\(\s*["'`]([A-Z_][A-Z0-9_]*)["'`]/g

/** Every env var read by name in non-test files under `apps/` and `bundled-apps/`. */
export function collectEnvReads(root: string = ROOT): Map<string, string[]> {
  const files: string[] = []
  for (const top of ["apps", "bundled-apps"]) walkSources(join(root, top), files)
  const reads = new Map<string, string[]>()
  for (const f of files) {
    const lines = readFileSync(f, "utf8").split("\n")
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i] ?? ""
      if (!line.includes("env")) continue
      for (const m of line.matchAll(ENV_READ)) {
        const name = m[1] ?? m[2] ?? m[3]
        if (!name) continue
        const at = `${relative(root, f)}:${i + 1}`
        const list = reads.get(name)
        if (list?.includes(at)) continue
        if (list) list.push(at)
        else reads.set(name, [at])
      }
    }
  }
  for (const list of reads.values()) list.sort()
  return reads
}

export interface EnvCollection {
  schema: EnvSchemaEntry[]
  groups: EnvGroup[]
  /** Read outside the schema and not exempt. */
  extra: EnvUsage[]
  /** Read outside the schema and exempt (by name or prefix). */
  exempt: string[]
}

export function collectEnvVars(
  root: string = ROOT,
  exempt: { names?: Record<string, string>; prefixes?: Record<string, string> } = {},
): EnvCollection {
  const { entries, groups } = collectEnvSchema(readFileSync(join(root, SOURCES.env), "utf8"), {
    root,
  })
  const inSchema = new Set(entries.map((e) => e.name))
  const extra: EnvUsage[] = []
  const exemptNames: string[] = []
  for (const [name, files] of collectEnvReads(root)) {
    if (inSchema.has(name)) continue
    if (isEnvExempt(name, exempt.names ?? ENV_EXEMPT, exempt.prefixes ?? ENV_EXEMPT_PREFIXES)) {
      exemptNames.push(name)
    } else extra.push({ name, files })
  }
  extra.sort((a, b) => a.name.localeCompare(b.name))
  exemptNames.sort()
  return { schema: entries, groups, extra, exempt: exemptNames }
}

export function renderEnv(c: EnvCollection): string {
  const out: string[] = [
    "Every variable the server reads at boot is a key of its environment schema. A missing required key, or a value of the wrong type, stops the process (exit 2 under the CLI).",
    "",
  ]
  for (const g of c.groups) {
    // Source order: a comment above a run of keys reads with the keys after it.
    const rows = c.schema.filter((e) => e.group === g.title)
    if (rows.length === 0) continue
    out.push(`## ${g.title ?? "Server"}`, "")
    if (g.intro) out.push(cell(g.intro), "")
    out.push(
      table(
        ["Name", "Type", "Default", "Required", "Description"],
        rows.map((e) => [
          code(e.name),
          code(e.type),
          e.default !== undefined ? code(e.default) : "",
          e.required ? "yes" : "no",
          cell(e.description),
        ]),
      ),
      "",
    )
  }
  out.push(
    "## Read outside the schema",
    "",
    "Variables the code under `apps/` and `bundled-apps/` reads directly (`process.env`, `Bun.env`, `envFlag`), without the schema validating them. Test and harness switches are left out (`docs/coverage-exempt.ts`).",
    "",
  )
  if (c.extra.length === 0) out.push("None.", "")
  else {
    out.push(
      table(
        ["Name", "Read in"],
        c.extra.map((u) => {
          const shown = u.files.slice(0, 3).map(code).join(", ")
          const more = u.files.length > 3 ? ` and ${u.files.length - 3} more` : ""
          return [code(u.name), `${shown}${more}`]
        }),
      ),
      "",
    )
  }
  return page(
    "Environment variables",
    "Every environment variable the Liaison server reads: type, default, whether it is required, and what it does.",
    `${code(SOURCES.env)} and the code under \`apps/\` and \`bundled-apps/\``,
    out.join("\n"),
  )
}

