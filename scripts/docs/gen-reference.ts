/** Leading comment lines of a node, comment markers stripped ('' = blank line). */
export function leadingCommentLines(node: ts.Node, sf: ts.SourceFile): string[] {
  const text = sf.getFullText()
  const ranges = ts.getLeadingCommentRanges(text, node.getFullStart()) ?? []
  const lines: string[] = []
  for (const r of ranges) {
    const raw = text.slice(r.pos, r.end)
    if (r.kind === ts.SyntaxKind.SingleLineCommentTrivia) {
      lines.push(raw.replace(/^\/\/\s?/, "").trimEnd())
    } else {
      const body = raw.replace(/^\/\*\*?/, "").replace(/\*\/$/, "")
      for (const l of body.split("\n")) lines.push(l.replace(/^\s*\*\s?/, "").trimEnd())
    }
  }
  // Trim blank edges.
  while (lines.length && lines[0]?.trim() === "") lines.shift()
  while (lines.length && lines[lines.length - 1]?.trim() === "") lines.pop()
  return lines
}

export function joinParagraph(lines: string[]): string {
  return lines
    .map((l) => l.trim())
    .filter((l) => l !== "")
    .join(" ")
    .replace(/\s+/g, " ")
    .trim()
}

const BANNER = /^──+\s*(.+?)\s*─*$/

