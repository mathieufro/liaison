/** Every generated page, repo-relative path → content. */
export function generateAll(root: string = ROOT): Map<string, string> {
  const manifests = loadManifests(root)
  return new Map([
    ["docs/reference/env.md", renderEnv(collectEnvVars(root))],
    ["docs/reference/cli.md", renderCli(COMMANDS)],
    [
      "docs/reference/config.md",
      renderConfig(collectConfigSchema(readFileSync(join(root, SOURCES.config), "utf8"), { root })),
    ],
    [
      "docs/reference/scopes.md",
      renderScopes(
        collectKernelScopes(readFileSync(join(root, SOURCES.scopes), "utf8"), SOURCES.scopes, root),
        manifests,
      ),
    ],
    ["docs/reference/app-settings.md", renderAppSettings(collectManifestSettings(root))],
    [
      "docs/reference/agent-tools.md",
      renderAgentTools(collectKernelTools(root), collectAgentTools(root)),
    ],
    ["docs/reference/setup.md", renderSetupReference(manifests)],
  ])
}

/**
 * Write `files` under `root`, or with `check` only compare. Returns the paths
 * that were (or, with `check`, would be) changed.
 */
export function writeOrCheck(root: string, files: Map<string, string>, check: boolean): string[] {
  const stale: string[] = []
  for (const [rel, content] of files) {
    const full = join(root, rel)
    const current = existsSync(full) ? readFileSync(full, "utf8") : null
    if (current === content) continue
    stale.push(rel)
    if (!check) {
      mkdirSync(dirname(full), { recursive: true })
      writeFileSync(full, content)
    }
  }
  return stale.sort()
}

export function run(argv: string[], root: string = ROOT): number {
  const check = argv.includes("--check")
  const stale = writeOrCheck(root, generateAll(root), check)
  if (check) {
    if (stale.length > 0) {
      process.stderr.write(
        `docs:gen --check: stale reference pages (run \`bun run docs:gen\`):\n${stale.map((s) => `  ${s}`).join("\n")}\n`,
      )
      return 1
    }
    process.stdout.write("docs:gen --check: reference pages are up to date\n")
    return 0
  }
  process.stdout.write(
    stale.length > 0 ? `docs:gen: wrote ${stale.join(", ")}\n` : "docs:gen: nothing to change\n",
  )
  return 0
}

if (import.meta.main) process.exit(run(process.argv.slice(2)))
