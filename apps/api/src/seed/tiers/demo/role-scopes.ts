/**
 * The scope bundle for a role. A fresh array each call: callers filter and
 * sort it, and the table must not be mutable through them.
 */
export function demoScopesForRole(role: DemoRole): string[] {
  return [...DEMO_ROLE_SCOPES[role]]
}

